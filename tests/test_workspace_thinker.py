# =============================================================================
# Gate 4: Sequence Padding Invariance
# =============================================================================

def test_workspace_padding_invariance():
    """Gate 4: Padding elements do not leak into valid residue coordinates."""
    torch.manual_seed(99)
    L_true = 16
    L_pad = 32
    d_single, d_pair, d_tok = 128, 64, 64

    s_short = torch.randn(1, L_true, d_single)
    z_short = torch.randn(1, L_true, L_true, d_pair)
    q_tokens = torch.randn(1, 16, d_tok)
    mask_short = torch.ones(1, L_true, dtype=torch.bool)

    s_pad = torch.zeros(1, L_pad, d_single)
    s_pad[:, :L_true, :] = s_short

    z_pad = torch.zeros(1, L_pad, L_pad, d_pair)
    z_pad[:, :L_true, :L_true, :] = z_short

    mask_pad = torch.zeros(1, L_pad, dtype=torch.bool)
    mask_pad[:, :L_true] = True

    cfg = WorkspaceThinkerConfig(d_h=128, d_single=d_single, d_pair=d_pair, d_tok=d_tok, num_steps=2)
    thinker = RecurrentWorkspaceThinker(cfg)
    thinker.eval()

    with torch.no_grad():
        out_short = thinker(s_short, z_short, q_tokens, mask=mask_short)
        out_pad = thinker(s_pad, z_pad, q_tokens, mask=mask_pad)

    trans_short = out_short["final_frames"].trans[:, :L_true, :]
    trans_pad = out_pad["final_frames"].trans[:, :L_true, :]

    diff = (trans_short - trans_pad).abs().max().item()
    print(f"\nMax translation difference under sequence padding: {diff:.6e} Å")
    assert diff < 1e-4, f"Padding leaked into structural coordinates: diff = {diff}"


