# =============================================================================
# Gate 1: SO(3) Manifold Guarantee
# =============================================================================

def test_so3_manifold_guarantee():
    """Gate 1: Verify so3_exp_map strictly produces valid rotation matrices R in SO(3)."""
    torch.manual_seed(123)

    # Test random tangent vectors covering small, typical, and large rotations
    omegas = [
        torch.zeros(5, 3),                        # Identity rotation (0 rad)
        torch.randn(10, 3) * 1e-6,                # Extremely small angles (< 1e-4 rad)
        torch.randn(20, 3) * 0.5,                 # Moderate angles
        torch.randn(20, 3) * 3.1415,              # Large angles (~pi rad)
    ]

    for omega in omegas:
        R = so3_exp_map(omega)
        batch_size = omega.shape[0]

        # 1. Orthonormality: R^T · R = I
        eye = torch.eye(3, dtype=omega.dtype, device=omega.device).unsqueeze(0).expand(batch_size, -1, -1)
        r_rt = torch.matmul(R, R.transpose(-1, -2))
        ortho_diff = (r_rt - eye).abs().max().item()
        assert ortho_diff < 1e-4, f"SO(3) orthonormality violated: max diff = {ortho_diff:.6e}"

        # 2. Proper rotation: det(R) = +1
        det = torch.linalg.det(R)
        det_diff = (det - 1.0).abs().max().item()
        assert det_diff < 1e-4, f"SO(3) determinant ≠ +1: max diff = {det_diff:.6e}"


# =============================================================================
# Gate 2: Extended Linear Chain Initialization
# =============================================================================

def test_extended_linear_chain_initialization():
    """Gate 2: Verify non-degenerate extended polypeptide initialization (3.8Å spacing)."""
    B, L = 3, 20
    frames = make_extended_linear_chain(batch_size=B, seq_len=L, bond_length=3.8)

    # 1. Verify rotation is Identity
    eye = torch.eye(3).unsqueeze(0).unsqueeze(0).expand(B, L, -1, -1)
    assert torch.allclose(frames.rot, eye), "Initial rotations must be identity matrices"

    # 2. Verify Cα spacing along x-axis
    for i in range(L - 1):
        delta = frames.trans[:, i + 1, :] - frames.trans[:, i, :]
        dist = torch.norm(delta, dim=-1)
        assert torch.allclose(dist, torch.tensor([3.8] * B), atol=1e-5), (
            f"Consecutive Cα spacing at residue {i} is not 3.8Å: {dist}"
        )
        assert torch.allclose(delta[:, 1:], torch.zeros(B, 2), atol=1e-5), (
            "Extended chain must align purely along x-axis at step 0"
        )


