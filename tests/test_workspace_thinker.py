# Gate 6: Multi-Step Supervision and Test-Time Compute Scaling
# =============================================================================

def test_test_time_compute_scaling(synthetic_thinker_inputs):
    """Gate 6: Verify model can execute dynamically at R ∈ {1, 2, 4, 8} without geometric explosion."""
    cfg = WorkspaceThinkerConfig(
        d_h=128,
        d_single=128,
        d_pair=64,
        d_tok=64,
        num_steps=4,
    )
    thinker = RecurrentWorkspaceThinker(cfg)

    s = synthetic_thinker_inputs["s"]
    z = synthetic_thinker_inputs["z"]
    q_tokens = synthetic_thinker_inputs["q_tokens"]
    mask = synthetic_thinker_inputs["mask"]

    # Target frames (mock native structure)
    target_frames = RigidFrames(
        rot=torch.eye(3).unsqueeze(0).unsqueeze(0).expand(2, 24, -1, -1),
        trans=torch.randn(2, 24, 3) * 5.0,
    )

    # 1. Forward pass with default R = 4
    out_default = thinker(s, z, q_tokens, mask=mask)
    assert len(out_default["trajectory"]) == 4

    # Compute multi-step FAPE loss
    loss_dict = thinker.compute_loss(out_default["trajectory"], target_frames, mask)
    loss = loss_dict["loss"]
    loss.backward()

    # Verify gradients reach shared reasoning block
    assert thinker.reasoning_block.head_dt.weight.grad is not None
    assert torch.isfinite(thinker.reasoning_block.head_dt.weight.grad).all()
    assert thinker.reasoning_block.head_domega.weight.grad is not None
    assert torch.isfinite(thinker.reasoning_block.head_domega.weight.grad).all()

    # 2. Test-time compute scaling: run with R = 1, 2, 4, 8
    thinker.eval()
    with torch.no_grad():
        for r_steps in [1, 2, 4, 8]:
            out_r = thinker(s, z, q_tokens, mask=mask, eval_steps=r_steps)
            assert len(out_r["trajectory"]) == r_steps

            final_trans = out_r["final_frames"].trans
            final_rot = out_r["final_frames"].rot

            # Verify no NaN or explosion
            assert not torch.isnan(final_trans).any(), f"NaN in translations at R={r_steps}"
            assert not torch.isnan(final_rot).any(), f"NaN in rotations at R={r_steps}"
            assert final_trans.abs().max() < 1000.0, f"Geometric explosion detected at R={r_steps}"


def test_so3_exp_map_gradient_numerical_stability():
    """Verify so3_exp_map backward gradients remain strictly finite across dtypes and input ranges.

    Prevents non-finite gradient regressions when training under mixed precision (AMP float16/bfloat16).
    """
    test_cases = [
        ("zeros", torch.zeros(2, 8, 3)),
        ("tiny_1e-8", torch.full((2, 8, 3), 1e-8)),
        ("small_1e-6", torch.full((2, 8, 3), 1e-6)),
        ("small_1e-5", torch.full((2, 8, 3), 1e-5)),
        ("small_1e-4", torch.full((2, 8, 3), 1e-4)),
        ("moderate_0.5", torch.randn(2, 8, 3) * 0.5),
        ("pi", torch.full((2, 8, 3), 3.14159265)),
        ("large_5", torch.randn(2, 8, 3) * 5.0),
    ]

    for name, tensor_val in test_cases:
        for dtype in [torch.float32, torch.float16, torch.bfloat16]:
            omega = tensor_val.clone().to(dtype).requires_grad_(True)
            rot = so3_exp_map(omega)
            loss = rot.sum()
            loss.backward()

            assert omega.grad is not None, f"Gradient is None for {name} ({dtype})"
            assert torch.isfinite(omega.grad).all(), (
                f"Non-finite gradient in so3_exp_map for {name} ({dtype}): {omega.grad}"
            )

